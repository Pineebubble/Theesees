const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const c=vm.createContext({console,structuredClone,Date,Map,document:{addEventListener(){}},uid:(()=>{let n=0;return()=>`b${++n}`;})()});
vm.runInContext(`let saved=true,formHandler,threadSource='h';const data={papers:[{id:'p'}],passages:[{id:'h',paperId:'p',quote:'Source quotation',location:'p. 3'}]};const esc=s=>String(s??'').replace(/</g,'&lt;');const getPaper=id=>data.papers.find(p=>p.id===id);const save=()=>saved;const modal=(a,b,c)=>{formHandler=c;};const closeModal=()=>{};const renderThread=()=>{};const actions=()=>'';const threadPassages=()=>data.passages;const conversationTurns=raw=>[{speaker:'User',body:raw}];`,c);
vm.runInContext(fs.readFileSync(__dirname+'/dist/conversation-blocks.js','utf8'),c);
const run=s=>vm.runInContext(s,c);
run('const cleanPDFBreaks=s=>s;');
run(`let t={transcript:'Original message',passageIds:['h']};composeBlock(t);formHandler(new Map([['body','First thought'],['role','Me'],['passage','h'],['key','on']]));composeBlock(t,{parentId:t.blocks[0].id});formHandler(new Map([['body','Pasted reply'],['role','AI']]));`);
assert.equal(run('t.blocks[1].parentId'),run('t.blocks[0].id'));
assert.equal(run('t.blocks[0].source.quote'),'Source quotation');
assert.match(run('threadedDiscussionView(t)'),/★ First thought/);
assert.match(run('blockTree(t)'),/Pasted reply/);
run(`composeBlock(t,{importIndex:0});formHandler(new Map([['body','Response to import'],['role','Me']]));`);
assert.equal(run('t.transcript'),'Original message');
run(`t.transcript='Changed import';`);
assert.match(run('threadedDiscussionView(t)'),/earlier version/);
run(`composeBlock(t,{editId:t.blocks[0].id});formHandler(new Map([['body','Revised thought'],['role','Me']]));`);
assert.equal(run('t.blocks[0].revisions[0].text'),'First thought');
run(`commitBlocks(t,()=>t.blocks[0].deleted=true);`);
assert(!run('blockTree(t)').includes('Comment removed'));
assert(!run('blockTree(t)').includes('>Restore</button>'));
assert.match(run('blockTree(t)'),/Pasted reply/);
run(`commitBlocks(t,()=>t.blocks[0].deleted=false);let before=JSON.stringify(t);saved=false;composeBlock(t);formHandler(new Map([['body','Unsaved'],['role','Me']]));`);
assert.equal(run('JSON.stringify(t)===before'),true);
assert.throws(()=>run(`formHandler(new Map([['body','   '],['role','Me']]))`),/Write or paste/);
run('t=JSON.parse(JSON.stringify(t));');
assert.match(run('blockTree(t)'),/Revised thought/);
console.log('PASS: threaded replies, source snapshots, key thoughts, import preservation, edit history, recoverable removal, save rollback, serialization.');
run(`saved=true;t={transcript:'',blocks:[{id:'root',parentId:null,anchor:null,text:'Opening',role:'Me',at:new Date().toISOString()},{id:'reply',parentId:'root',anchor:null,text:'Second',role:'AI',at:new Date().toISOString()},{id:'deep',parentId:'reply',anchor:null,text:'Third',role:'Me',at:new Date().toISOString()}]};`);
assert.equal(run("conversationRoot(t,t.blocks[2]).id"),'root');
const flat=run('blockTree(t)');
assert.equal((flat.match(/class="flat-thread"/g)||[]).length,1);
assert.equal((flat.match(/<article /g)||[]).length,3);
assert(!flat.includes('block-replies'));
assert(flat.indexOf('</article>')<flat.indexOf('id="block-reply"'));
run(`composeBlock(t,{parentId:'reply',subthread:true});formHandler(new Map([['body','Side question'],['role','Me']]));let branch=t.blocks.at(-1);composeBlock(t,{parentId:branch.id});formHandler(new Map([['body','Side answer'],['role','AI']]));`);
assert.equal(run('conversationRoot(t,t.blocks.at(-1)).id'),run('branch.id'));
assert.equal((run('blockTree(t)').match(/class="optional-subthread tucked-subthread"/g)||[]).length,1);
assert(run('blockTree(t)').indexOf('Side question')<run('blockTree(t)').indexOf('Third'));
run(`composeBlock(t,{parentId:'deep'});formHandler(new Map([['body','Main conversation continues'],['role','AI']]));`);
assert.equal(run('conversationRoot(t,t.blocks.at(-1)).id'),'root');
assert.equal(run('t.blocks[2].parentId'),'reply');
assert.match(run('blockTree(t)'),/Start subthread/);
console.log('PASS: legacy reply chains render flat, explicit branches stay separate, ordinary replies continue in their thread, parent links preserved.');
